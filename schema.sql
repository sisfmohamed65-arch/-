-- شغّل هذا الملف من Supabase SQL Editor بعد إنشاء حساب المالك في Authentication.
create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  price numeric(10,2) not null check (price >= 0),
  category text not null,
  image_url text,
  created_at timestamptz not null default now()
);
create table if not exists public.store_settings (
  id integer primary key check (id = 1),
  store_name text not null default 'زهرة حماة',
  whatsapp_number text not null default '',
  messenger_url text not null default '',
  facebook_url text not null default ''
);
insert into public.store_settings (id, store_name, whatsapp_number)
values (1, 'زهرة حماة', '') on conflict (id) do nothing;

-- جدول المالكين المصرح لهم فقط
create table if not exists public.admins (
  user_id uuid primary key references auth.users(id) on delete cascade
);
-- غيّر البريد إلى بريد حساب المالك الذي أنشأته في Supabase Authentication
insert into public.admins(user_id)
select id from auth.users where email = 'OWNER_EMAIL_HERE'
on conflict do nothing;

alter table public.products enable row level security;
alter table public.store_settings enable row level security;
alter table public.admins enable row level security;

create policy "public can read products" on public.products
for select to anon, authenticated using (true);
create policy "public can read store settings" on public.store_settings
for select to anon, authenticated using (true);

create policy "only admins manage products" on public.products
for all to authenticated
using (exists (select 1 from public.admins a where a.user_id = auth.uid()))
with check (exists (select 1 from public.admins a where a.user_id = auth.uid()));

create policy "only admins manage store settings" on public.store_settings
for all to authenticated
using (exists (select 1 from public.admins a where a.user_id = auth.uid()))
with check (exists (select 1 from public.admins a where a.user_id = auth.uid()));

-- لا نمنح صلاحية قراءة جدول admins للزوار.

